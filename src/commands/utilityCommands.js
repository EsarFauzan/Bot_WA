function formatZikir(data) {
    let teks = `*${data.judul}*\n`;
    teks += '─────────────────────\n\n';
    data.isi.forEach((z, i) => {
        teks += `*${i + 1}. ${z.nama}*\n`;
        teks += `${z.arab}\n`;
        teks += `_${z.latin}_\n\n`;
        teks += `📖 ${z.arti}\n`;
        teks += `✨ ${z.faedah}\n\n`;
        teks += '─────────────────────\n';
    });
    return teks;
}

function buildZikirMessageByType(type) {
    if (!ZIKIR[type]) return null;
    return formatZikir(ZIKIR[type]);
}

function buildRandomZikirMessage(options = {}) {
    const includeHint = options.includeHint !== false;
    const z = RANDOM_ZIKIR[Math.floor(Math.random() * RANDOM_ZIKIR.length)];

    let teks = '📿 *ZIKIR RANDOM*\n';
    teks += '─────────────────────\n\n';
    teks += `${z.arab}\n\n`;
    teks += `_${z.latin}_\n\n`;
    teks += `📖 ${z.arti}\n\n`;
    teks += `✨ *Faedah:* ${z.faedah}\n\n`;
    teks += '─────────────────────\n';
    if (includeHint) {
        teks += '_Ketik !zikir random lagi untuk zikir lain 😊_';
    }

    return teks;
}

function createUtilityCommandsHandler(deps) {
    const {
        axios,
        sholatModes = new Map(),
        saveSholatModes = () => {},
        groupReminders = new Map(),
        saveReminders = () => {},
        zikirAutoTargets = new Map(),
        saveZikirAutoTargets = () => {}
    } = deps;

    return async function handleUtilityCommands(ctx) {
        const { cmd, msg } = ctx;

    if (cmd.startsWith('!cuaca ')) {
        const kota = msg.body.trim().split(' ').slice(1).join(' ').trim();
        if (!kota) {
            await msg.reply('Cara pakai: *!cuaca [nama kota]*\nContoh: !cuaca Palu');
            return true;
        }

        try {
            const chat = await msg.getChat();
            chat.sendStateTyping();
            const apiKey = process.env.OPENWEATHER_API_KEY;
            if (!apiKey) {
                await msg.reply('API key cuaca belum diset 😹');
                return true;
            }

            const res = await axios.get(`https://api.openweathermap.org/data/2.5/weather?q=${encodeURIComponent(kota)}&appid=${apiKey}&units=metric&lang=id`);
            const d = res.data;
            const cuacaEmoji = {
                Clear: '☀️', Clouds: '☁️', Rain: '🌧️',
                Drizzle: '🌦️', Thunderstorm: '⛈️', Snow: '❄️',
                Mist: '🌫️', Fog: '🌫️', Haze: '🌫️'
            };
            const emoji = cuacaEmoji[d.weather[0].main] || '🌡️';
            const teks = `${emoji} *Cuaca ${d.name}, ${d.sys.country}*\n─────────────────────\n🌡️ Suhu: *${Math.round(d.main.temp)}°C* (terasa ${Math.round(d.main.feels_like)}°C)\n💧 Kelembaban: *${d.main.humidity}%*\n💨 Angin: *${(d.wind.speed * 3.6).toFixed(1)} km/jam*\n☁️ Kondisi: *${d.weather[0].description}*\n👁️ Jarak pandang: *${(d.visibility / 1000).toFixed(1)} km*\n─────────────────────`;
            await msg.reply(teks);
        } catch (err) {
            if (err.response?.status === 404) {
                msg.reply(`Kota "${kota}" tidak ditemukan 😹\nCoba tulis dalam bahasa Inggris, contoh:\n!cuaca Makassar\n!cuaca Jakarta`);
            } else {
                msg.reply('Aduh gagal ambil data cuaca sy 😹 coba lagi yaa');
            }
        }

        return true;
    }

    if (cmd === '!cuaca') {
        msg.reply('Cara pakai: *!cuaca [nama kota]*\n\nContoh:\n!cuaca Palu\n!cuaca Jakarta\n!cuaca Makassar');
        return true;
    }

    if (cmd.startsWith('!sholat mode')) {
        const sub = cmd.replace('!sholat mode', '').trim();

        if (!sub) {
            const modeNow = sholatModes.get(msg.from) === 'puasa' ? 'puasa' : 'normal';
            await msg.reply(`🕌 *Mode Sholat Saat Ini*\nMode: *${modeNow}*\n\nPerintah:\n*!sholat mode puasa*\n*!sholat mode normal*`);
            return true;
        }

        if (sub !== 'puasa' && sub !== 'normal' && sub !== 'nonpuasa') {
            await msg.reply('Mode tidak valid. Gunakan *puasa* atau *normal*.');
            return true;
        }

        const modeFinal = sub === 'puasa' ? 'puasa' : 'normal';
        const isPuasaMode = modeFinal === 'puasa';
        sholatModes.set(msg.from, modeFinal);
        saveSholatModes();

        if (groupReminders.has(msg.from)) {
            const info = groupReminders.get(msg.from) || {};
            groupReminders.set(msg.from, {
                ...info,
                puasaMode: isPuasaMode
            });
            saveReminders();
        }

        await msg.reply(`✅ Mode sholat di chat ini diatur ke *${modeFinal}*.\n${isPuasaMode ? 'Imsak dan buka puasa akan ditampilkan.' : 'Imsak dan buka puasa disembunyikan.'}`);
        return true;
    }

    if (cmd.startsWith('!sholat ')) {
        const kota = msg.body.trim().split(' ').slice(1).join(' ').trim();
        if (!kota) {
            await msg.reply('Cara pakai: *!sholat [nama kota]*\nContoh: !sholat Palu');
            return true;
        }

        try {
            const chat = await msg.getChat();
            chat.sendStateTyping();
            const cariRes = await axios.get(`https://api.myquran.com/v2/sholat/kota/cari/${encodeURIComponent(kota)}`);
            const kotaList = cariRes.data?.data;
            if (!kotaList || kotaList.length === 0) {
                await msg.reply(`Kota "${kota}" tidak ditemukan 😹\nCoba nama kota lain jo`);
                return true;
            }
            const kotaData = kotaList[0];
            const today = new Date();
            const tgl = today.toISOString().split('T')[0];
            const jadwalRes = await axios.get(`https://api.myquran.com/v2/sholat/jadwal/${kotaData.id}/${tgl}`);
            const jadwal = jadwalRes.data?.data?.jadwal;
            if (!jadwal) {
                await msg.reply('Gagal ambil jadwal sholat 😹 coba lagi jo');
                return true;
            }

            const hariNama = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
            const isPuasaMode = sholatModes.get(msg.from) === 'puasa';
            let teks = `🕌 *Jadwal Sholat ${kotaData.lokasi}*\n📅 ${hariNama[today.getDay()]}, ${jadwal.tanggal}\n⚙️ Mode: *${isPuasaMode ? 'puasa' : 'normal'}*\n─────────────────────\n`;
            if (isPuasaMode) teks += `🔔 Imsak   : *${jadwal.imsak}*\n`;
            teks += `🌅 Subuh   : *${jadwal.subuh}*\n`;
            teks += `🌄 Terbit  : *${jadwal.terbit}*\n`;
            teks += `☀️ Dhuha   : *${jadwal.dhuha}*\n`;
            teks += `🌞 Dzuhur  : *${jadwal.dzuhur}*\n`;
            teks += `🌇 Ashar   : *${jadwal.ashar}*\n`;
            teks += `${isPuasaMode ? '🍽️ Buka' : '🌆 Maghrib'}  : *${jadwal.maghrib}*\n`;
            teks += `🌙 Isya    : *${jadwal.isya}*\n`;
            teks += '─────────────────────';
            if (isPuasaMode) {
                teks += '\n💡 _Imsak = batas makan sahur_\n🍽️ _Buka puasa = waktu maghrib_';
            }
            await msg.reply(teks);
        } catch (err) {
            console.error('Error !sholat:', err.message);
            msg.reply('Aduh gagal ambil jadwal sholat sy 😹 coba lagi yaa');
        }

        return true;
    }

    if (cmd === '!sholat') {
        msg.reply('Cara pakai: *!sholat [nama kota]*\n\nContoh:\n!sholat Palu\n!sholat Jakarta\n!sholat Makassar\n\nMode:\n!sholat mode puasa\n!sholat mode normal\n!sholat mode');
        return true;
    }

    if (cmd.startsWith('!quran')) {
        const args = msg.body.trim().split(' ').slice(1);
        if (args.length === 0) {
            await msg.reply('📖 *MENU AL-QURAN*\n─────────────────────\n*!quran [surah]* → Info detail surah\n*!quran [surah] [ayat]* → Baca ayat spesifik\n\n📌 *Contoh:*\n*!quran 114 1* → Surah An-Nas ayat 1\n*!quran 1 7* → Surah Al-Fatihah ayat 7\n*!quran 36* → Info Surah Yasin\n\n_Catatan: Gunakan nomor surah (1-114)_');
            return true;
        }

        const surahNomor = parseInt(args[0]);
        const ayatNomor = args.length > 1 ? parseInt(args[1]) : null;

        if (isNaN(surahNomor) || surahNomor < 1 || surahNomor > 114) {
            await msg.reply('Nomor surah salah 😹. Harap masukkan nomor surah dari 1 sampai 114.');
            return true;
        }

        try {
            const chat = await msg.getChat();
            chat.sendStateTyping();

            const res = await axios.get(`https://equran.id/api/v2/surat/${surahNomor}`);
            const dataSurah = res.data?.data;

            if (!dataSurah) {
                await msg.reply('Gagal mengambil data surah 😹. Coba lagi nanti.');
                return true;
            }

            if (ayatNomor) {
                if (isNaN(ayatNomor) || ayatNomor < 1 || ayatNomor > dataSurah.jumlahAyat) {
                    await msg.reply(`Nomor ayat salah 😹. Surah *${dataSurah.namaLatin}* hanya memiliki *${dataSurah.jumlahAyat}* ayat.`);
                    return true;
                }

                const ayat = dataSurah.ayat[ayatNomor - 1];
                let teks = `📖 *${dataSurah.namaLatin} (${dataSurah.nama})* - Ayat ${ayat.nomorAyat}\n`;
                teks += '─────────────────────\n\n';
                teks += `${ayat.teksArab}\n\n`;
                teks += `_${ayat.teksLatin}_\n\n`;
                teks += `📖 *Terjemahan:*\n${ayat.teksIndonesia}\n\n`;
                teks += '─────────────────────\n';
                teks += `_Jumlah Ayat: ${dataSurah.jumlahAyat} | Turun di: ${dataSurah.tempatTurun}_\n`;
                await msg.reply(teks);
            } else {
                let teks = `📖 *${dataSurah.namaLatin} (${dataSurah.nama})*\n`;
                teks += '─────────────────────\n';
                teks += `Arti: ${dataSurah.arti}\n`;
                teks += `Jumlah Ayat: ${dataSurah.jumlahAyat}\n`;
                teks += `Tempat Turun: ${dataSurah.tempatTurun}\n\n`;
                teks += `💡 *Deskripsi:*\n${dataSurah.deskripsi.replace(/<[^>]*>?/gm, '').replace(/&nbsp;/g, ' ').substring(0, 400)}...\n\n`;
                teks += `_Untuk membaca ayat, gunakan format: !quran ${surahNomor} [nomor_ayat]_\n`;
                teks += `_Contoh: !quran ${surahNomor} 1_`;
                await msg.reply(teks);
            }
        } catch (err) {
            console.error('Error !quran:', err.message);
            msg.reply('Aduh gagal mengambil data Al-Quran 😹. Sedang ada masalah dari API pusat.');
        }

        return true;
    }

    if (cmd.startsWith('!github ')) {
        const username = msg.body.trim().split(' ')[1]?.trim();
        if (!username) {
            await msg.reply('Cara pakai: *!github [username]*\nContoh: !github torvalds');
            return true;
        }
        try {
            const chat = await msg.getChat();
            chat.sendStateTyping();

            const [userRes, repoRes] = await Promise.all([
                axios.get(`https://api.github.com/users/${username}`),
                axios.get(`https://api.github.com/users/${username}/repos?sort=updated&per_page=5`)
            ]);

            const u = userRes.data;
            const repos = repoRes.data;

            let teks = `👨‍💻 *GitHub: ${u.login}*\n`;
            if (u.name) teks += `📛 Nama     : ${u.name}\n`;
            if (u.bio) teks += `💬 Bio      : ${u.bio}\n`;
            if (u.company) teks += `🏢 Company  : ${u.company}\n`;
            if (u.location) teks += `📍 Lokasi   : ${u.location}\n`;
            teks += '─────────────────────\n';
            teks += `📁 Repo     : *${u.public_repos}*\n`;
            teks += `❤️ Followers: *${u.followers}*\n`;
            teks += `👥 Following: *${u.following}*\n`;
            teks += '─────────────────────\n';

            if (repos.length > 0) {
                teks += '🔥 *5 Repo Terbaru:*\n';
                for (const r of repos) {
                    const stars = r.stargazers_count > 0 ? ` ⭐${r.stargazers_count}` : '';
                    const lang = r.language ? ` [${r.language}]` : '';
                    teks += `• *${r.name}*${lang}${stars}\n`;
                }
                teks += '─────────────────────\n';
            }

            teks += `🔗 ${u.html_url}`;
            await msg.reply(teks);
        } catch (err) {
            if (err.response?.status === 404) {
                msg.reply(`User GitHub *"${username}"* tidak ditemukan 😹`);
            } else if (err.response?.status === 403) {
                msg.reply('Rate limit GitHub tercapai 😹 Coba lagi beberapa menit lagi');
            } else {
                msg.reply('Gagal ambil data GitHub 😹 coba lagi yaa');
            }
        }

        return true;
    }

    if (cmd === '!github') {
        msg.reply('Cara pakai: *!github [username]*\n\nContoh:\n!github torvalds\n!github EsarFauzan');
        return true;
    }

    if (cmd.startsWith('!anime ')) {
        const query = msg.body.trim().slice(7).trim();
        if (!query) {
            await msg.reply('Cara pakai: *!anime [judul]*\nContoh: !anime naruto');
            return true;
        }

        try {
            const chat = await msg.getChat();
            chat.sendStateTyping();
            await msg.reply(`🔍 Bentar sy cari *${query}* dulu 🤭 sabar jo...`);

            const res = await axios.get(`https://api.jikan.moe/v4/anime?q=${encodeURIComponent(query)}&limit=5&sfw=true`, {
                timeout: 15000
            });

            const results = res.data?.data;
            if (!results || results.length === 0) {
                await msg.reply(`Anime *"${query}"* tidak ditemukan 😹\nCoba judul lain jo`);
                return true;
            }

            let teks = `🎌 *Hasil Pencarian: "${query}"*\n`;
            teks += `📊 Ditemukan ${results.length} anime\n`;
            teks += '─────────────────────\n\n';

            for (let i = 0; i < results.length; i++) {
                const a = results[i];
                const searchTitle = a.title_indonesian || a.title_english || a.title || '';
                const kusonimeUrl = `https://kusonime.com/?s=${encodeURIComponent(searchTitle)}`;
                const genres = a.genres?.map((g) => g.name).join(', ') || '-';
                const eps = a.episodes ? `${a.episodes} eps` : '?? eps';
                const tahun = a.year || a.aired?.prop?.from?.year || '-';

                teks += `*${i + 1}. ${a.title}*\n`;
                if (a.title_indonesian && a.title_indonesian !== a.title) teks += `📝 ${a.title_indonesian}\n`;
                teks += `📺 ${a.type || '-'} • ${eps} • ${tahun}\n`;
                teks += `📌 Status : ${a.status || '-'}\n`;
                if (a.score) teks += `⭐ Score  : ${a.score}/10\n`;
                teks += `🎭 Genre  : ${genres}\n`;
                teks += `🔗 MAL    : ${a.url}\n`;
                teks += `⬇️ Download: ${kusonimeUrl}\n\n`;
            }

            teks += '─────────────────────\n';
            teks += '_Data: MyAnimeList | Download: Kusonime_';

            await msg.reply(teks);
        } catch (err) {
            console.error('Error !anime:', err.message);
            if (err.code === 'ETIMEDOUT' || err.code === 'ECONNABORTED') {
                msg.reply('Koneksi timeout 😹 coba lagi jo');
            } else if (err.response?.status === 429) {
                msg.reply('Terlalu banyak request 😹 tunggu sebentar lalu coba lagi jo');
            } else {
                msg.reply('Aduh gagal cari anime ee 😹 coba lagi jo');
            }
        }

        return true;
    }

    if (cmd === '!anime') {
        msg.reply('Cara pakai: *!anime [judul]*\n\nContoh:\n!anime naruto\n!anime one piece\n!anime attack on titan');
        return true;
    }

    if (cmd === '!zikir' || cmd.startsWith('!zikir ')) {
        const sub = cmd.slice(7).trim();

        if (!sub || sub === 'help') {
            msg.reply('📿 *MENU ZIKIR & DOA*\n─────────────────────\n\n🌅 *!zikir pagi* → Zikir pagi lengkap\n🌆 *!zikir sore* → Zikir sore lengkap\n📿 *!zikir harian* → Zikir harian setelah sholat\n🌙 *!zikir tidur* → Doa sebelum tidur\n🍽️ *!zikir makan* → Doa makan & minum\n🎲 *!zikir random* → Satu zikir acak beserta faedahnya\n\n🤖 *AUTO ZIKIR*\n*!zikir auto on* → Aktifkan kirim otomatis di chat ini\n*!zikir auto off* → Matikan kirim otomatis\n*!zikir auto* → Lihat status & jadwal hari ini\n\n─────────────────────\n_Semoga istiqomah ya 😊_');
            return true;
        }

        if (sub === 'auto on') {
            if (!groupReminders.has(msg.from)) {
                await msg.reply('Aktifkan dulu reminder sholat di chat ini dengan *!reminder on [kota]* supaya bot tahu jadwal sholatnya.');
                return true;
            }

            zikirAutoTargets.set(msg.from, true);
            saveZikirAutoTargets();
            await msg.reply('✅ Auto zikir aktif di chat ini.\n\nJadwal tetap:\n• Zikir pagi 05:00\n• Zikir sore 16:00\n• Zikir tidur 23:00\n\nZikir random otomatis:\n• 5 menit setelah Subuh\n• 5 menit setelah Dzuhur\n• 5 menit setelah Ashar\n• 5 menit setelah Maghrib\n• 5 menit setelah Isya');
            return true;
        }

        if (sub === 'auto off') {
            if (!zikirAutoTargets.has(msg.from)) {
                await msg.reply('Auto zikir belum aktif di chat ini.');
                return true;
            }
            zikirAutoTargets.delete(msg.from);
            saveZikirAutoTargets();
            await msg.reply('❌ Auto zikir dimatikan di chat ini.');
            return true;
        }

        if (sub === 'auto' || sub === 'auto status') {
            const isActive = zikirAutoTargets.has(msg.from);
            const reminderStatus = groupReminders.has(msg.from)
                ? '✅ Reminder sholat aktif'
                : '❌ Reminder sholat belum aktif';
            await msg.reply(`📿 *Status Auto Zikir*\n─────────────────────\nStatus: ${isActive ? '✅ Aktif' : '❌ Tidak aktif'}\n${reminderStatus}\n\nJadwal tetap:\n• Zikir pagi 05:00\n• Zikir sore 16:00\n• Zikir tidur 23:00\n\nZikir random otomatis:\n• 5 menit setelah Subuh\n• 5 menit setelah Dzuhur\n• 5 menit setelah Ashar\n• 5 menit setelah Maghrib\n• 5 menit setelah Isya`);
            return true;
        }

        if (ZIKIR[sub]) {
            msg.reply(buildZikirMessageByType(sub));
            return true;
        }

        if (sub === 'random') {
            msg.reply(buildRandomZikirMessage());
            return true;
        }

        msg.reply('Pilihan tidak ada 😹\n\nKetik *!zikir* untuk lihat daftar pilihan');
        return true;
    }

        return false;
    };
}

